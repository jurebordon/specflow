#!/usr/bin/env node
// Hook: SessionEnd
// Saves a session state snapshot for continuity between sessions.

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const specflow = require('./specflow-config.cjs');

function execGit(cmd, cwd) {
  try {
    return execSync(cmd, { cwd, encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }).trim();
  } catch {
    return '';
  }
}

async function main() {
  let input = '';
  for await (const chunk of process.stdin) input += chunk;
  const data = JSON.parse(input);

  const cwd = data.cwd || process.env.CLAUDE_PROJECT_DIR || process.cwd();
  const cfg = specflow.load(cwd);
  if (!cfg) process.exit(0);

  const docsPath = specflow.docsPath(cfg);
  if (!docsPath) process.exit(0);

  const logName = path.basename(specflow.docFile(cfg, 'Session Log', 'SESSION_LOG.md'));
  const date = new Date().toISOString().split('T')[0];
  const branch = execGit('git branch --show-current', cfg.root) || 'unknown';
  const modifiedFiles = execGit('git diff --name-only HEAD', cfg.root);

  const fileList = modifiedFiles
    ? modifiedFiles.split('\n').filter(Boolean).map((f) => '- ' + f).join('\n')
    : '- No modified files detected';

  const content =
    '# Session State Snapshot\n\n' +
    '> Auto-generated by the SpecFlow session-end hook. Review and incorporate into ' + logName + '.\n\n' +
    '**Date**: ' + date + '\n' +
    '**Branch**: ' + branch + '\n\n' +
    '## Modified Files\n\n' +
    fileList + '\n\n' +
    '---\n\n' +
    '*This file is overwritten each session. Transfer relevant details to ' + logName + '.*\n';

  try {
    if (!fs.existsSync(docsPath)) {
      fs.mkdirSync(docsPath, { recursive: true });
    }
    fs.writeFileSync(path.join(docsPath, '.session-state.md'), content, 'utf8');
  } catch (err) {
    process.stderr.write('session-end-persist: could not write state file: ' + err.message + '\n');
  }

  process.exit(0);
}

main().catch((err) => {
  process.stderr.write('session-end-persist: ' + err.message + '\n');
  process.exit(0);
});
